#include <iostream>
using namespace std;

int main() {
    int a = 10, b = 5;
    int sum = a + b;

    cout << sum << endl;//or place of sum we can write (a+b)
    cout << "difference = " << (a-b) << endl;
    cout << "product = " << (a*b) << endl;
    cout << "division = " << (a/b) << endl;
    cout << "modulo = " << (a%b) << endl;
    return 0;
}